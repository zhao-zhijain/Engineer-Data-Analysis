# ==========================================
# 任务 1：学习字典 (Dictionary)
# 字典就是用来存“键值对”的，非常适合存工程参数
# ==========================================
print("=== 任务 1：工程参数字典 ===")
# 创建一个名为 project 的字典
project = {
    "项目名称": "西建大实训楼",
    "楼层数": 6,
    "混凝土用量(吨)": 1200,
    "项目经理": "赵同学"
}

# 打印字典里的具体内容
print("项目名字叫：", project["项目名称"])
print("混凝土总共用了：", project["混凝土用量(吨)"], "吨")


# ==========================================
# 任务 2：学习文件读写 (File I/O)
# 学会用代码自动生成文件，并读取里面的内容
# ==========================================
print("\n=== 任务 2：材料清单文件读写 ===")
# 1. 用代码自动在电脑里生成一个 txt 文件，并写入内容
# encoding="utf-8" 是为了防止中文乱码
with open("material_list.txt", "w", encoding="utf-8") as file:
    file.write("钢材: 100吨\n")
    file.write("水泥: 200吨\n")
    file.write("木材: 50立方米\n")

print("文件 'material_list.txt' 已成功生成！")

# 2. 读取刚才生成的文件内容，并打印在屏幕上
with open("material_list.txt", "r", encoding="utf-8") as file:
    content = file.read()
    print("--- 读取到的材料清单如下 ---")
    print(content)


# ==========================================
# 任务 3：初识 Pandas（处理数据的神兵利器）
# ==========================================
print("=== 任务 3：Pandas 数据表格 ===")
# 导入 pandas 库，并简写为 pd
import pandas as pd

# 准备一些数据（用字典的形式）
data = {
    "材料名称": ["钢材", "水泥", "木材"],
    "数量": [100, 200, 50],
    "单位": ["吨", "吨", "立方米"]
}

# 把字典变成一张表格 (DataFrame)
df = pd.DataFrame(data)

print("--- 这是 Pandas 生成的表格 ---")
print(df) # 打印表格

# 算一下所有材料的“数量”加起来是多少
total_count = df["数量"].sum()
print("所有材料的总数量是：", total_count)
